import assert from 'node:assert/strict';
import test from 'node:test';
import { grade, makePaper, makePortfolioCase } from '../src/bank.js';

const money = value => Number(value.replace(/[€,\s]/g, ''));
const amountsIn = text => [...text.matchAll(/€[\d,]+/g)].map(match => money(match[0]));
const percent = value => `${Number(value.toFixed(1))}%`;

function correctText(paper, question) {
  const selected = paper.key[question.id];
  assert.equal(selected.length, 1);
  return question.options.find(option => option.id === selected[0]).text;
}
function question(paper, prefix) {
  const matches = paper.questions.filter(q => q.prompt.startsWith(prefix));
  assert.equal(matches.length, 1, `one question starts with ${prefix}`);
  return matches[0];
}
function tableAmounts(q) {
  assert.ok(q.table, `missing table for ${q.prompt}`);
  const rows = new Map(q.table.rows.map(([label, value]) => [label, money(value)]));
  return rows;
}

test('monthly P&L supports the original figures and bounded revenue/overhead range edges', () => {
  const original = makePortfolioCase(120000, 35, 18000);
  assert.deepEqual(original.table.rows, [
    ['Revenue (client billing)', '€120,000'],
    ['Direct Costs (consultant salaries + charges)', '€78,000'],
    ['Gross Margin', '€42,000'],
    ['Allocated Overhead (office, support functions)', '€18,000'],
    ['Operating Result (Contribution)', '€24,000']
  ]);
  for (const [revenue, margin, overhead] of [[90000, 28, 7200], [300000, 46, 72000]]) {
    const sample = makePortfolioCase(revenue, margin, overhead);
    assert.equal(sample.directCosts + sample.gross, revenue);
    assert.equal(sample.contribution, sample.gross - overhead);
    assert.ok(sample.contribution > 0);
  }
});

test('each private paper preserves all 15 source identities, two sections, opaque IDs and private keys', () => {
  const paper = makePaper();
  const ids = new Set();
  assert.deepEqual(paper.questions.map(q => q.section), [
    ...Array(8).fill('Foundations'), ...Array(7).fill('Applied Reading')
  ]);
  const prefixes = [
    'What does P&L stand for?',
    'At Amaris, Revenue is primarily generated by:',
    'In consulting, Gross Margin is best defined as:',
    'A consultant is billed to a client at ',
    'A consultant bills ',
    'As a Business Manager at Amaris, which of the following is considered a direct cost on your P&L?',
    'One of your consultants is on the bench ',
    'You manage a team of ',
    'What is the Gross Margin % for this portfolio?',
    'One consultant (monthly cost: ',
    'Your Gross Margin % has dropped from ',
    'You have two consultants in your portfolio.',
    'A client asks you to reduce the billing rate by ',
    'As a Business Manager, which of the following actions has the most direct positive impact on your Gross Margin?',
    'You are comparing two Business Managers'
  ];
  const concepts = prefixes.map(prefix => question(paper, prefix));
  for (const q of paper.questions) {
    assert.equal(q.options.length, 4);
    assert.equal(new Set(q.options.map(o => o.text)).size, 4, q.prompt);
    assert.ok(correctText(paper, q));
    ids.add(q.id);
    for (const option of q.options) {
      assert.deepEqual(Object.keys(option).sort(), ['id', 'text']);
      ids.add(option.id);
    }
  }
  assert.equal(ids.size, 75);
  for (const id of ids) assert.match(id, /^[a-f\d-]{36}$/i);
  assert.deepEqual(Object.keys(paper.key).sort(), paper.questions.map(q => q.id).sort());
  assert.equal(concepts.length, 15);
  assert.ok(concepts.slice(0, 8).every(q => q.section === 'Foundations'));
  assert.ok(concepts.slice(8).every(q => q.section === 'Applied Reading'));
  assert.deepEqual(Object.keys(concepts[8]).sort(), ['id', 'options', 'prompt', 'section', 'table']);
  assert.deepEqual(Object.keys(concepts[9]).sort(), ['id', 'options', 'prompt', 'section', 'table']);
});

