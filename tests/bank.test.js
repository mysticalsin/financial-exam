test('grading accepts only the issued option for each question and gives no partial credit', () => {
  const paper = makePaper();
  const [first, second, third, fourth] = paper.questions;
  assert.equal(grade(paper, paper.key), 15);
  assert.equal(grade(paper, {}), 0);
  assert.equal(grade(paper, null), 0);
  const answers = structuredClone(paper.key);
  answers[first.id] = [paper.key[first.id][0], paper.key[first.id][0]];
  answers[second.id] = [paper.key[third.id][0]];
  answers[third.id] = true;
  delete answers[fourth.id];
  answers.score = 15;
  assert.equal(grade(paper, answers), 11);
  assert.equal(grade(makePaper(), paper.key), 0);
});

test('generated cases recompute from rendered figures and keep the shared P&L coherent', () => {
  const portfolioVariants = new Set();
  let alphaWins = 0;
  let betaWins = 0;
  let bmAlphaWins = 0;
  let bmBetaWins = 0;
  let highRateAlsoHigherRevenue = 0;
  let highRateHasLowerRevenue = 0;
  let q9Fallbacks = 0;
  for (let iteration = 0; iteration < 1500; iteration++) {
    const paper = makePaper();
    const q4 = question(paper, 'A consultant is billed to a client at ');
    const q5 = question(paper, 'A consultant bills ');
    const [billing, cost] = amountsIn(q4.prompt);
    const [repeatBilling, repeatCost] = amountsIn(q5.prompt);
    assert.deepEqual([repeatBilling, repeatCost], [billing, cost], 'Q4/Q5 share one daily case');
    assert.equal(correctText(paper, q4), `€${(billing - cost).toLocaleString('en-GB')}`);
    assert.equal(correctText(paper, q5), percent((billing - cost) / billing * 100));

    const q8 = question(paper, 'You manage a team of ');
    const team = Number(q8.prompt.match(/team of (\d+)/)[1]);
    const [monthlyBilling, directCost] = amountsIn(q8.prompt);
    assert.equal(correctText(paper, q8), `€${(team * monthlyBilling - directCost).toLocaleString('en-GB')}`);

    const q9 = question(paper, 'What is the Gross Margin % for this portfolio?');
    const q10 = question(paper, 'One consultant (monthly cost: ');
    const p9 = tableAmounts(q9);
    const p10 = tableAmounts(q10);
    assert.deepEqual([...p10], [...p9], 'Q9/Q10 share the same issued P&L');
    const revenue = p9.get('Revenue (client billing)');
    const direct = p9.get('Direct Costs (consultant salaries + charges)');
    const gross = p9.get('Gross Margin');
    const overhead = p9.get('Allocated Overhead (office, support functions)');
    const contribution = p9.get('Operating Result (Contribution)');
    assert.equal(gross, revenue - direct);
    assert.equal(contribution, gross - overhead);
    assert.ok(contribution > 0);
    assert.equal(correctText(paper, q9), percent(gross / revenue * 100));
    const expectedQ9Choices = new Set([
      percent(gross / revenue * 100),
      percent(direct / revenue * 100),
      percent(contribution / revenue * 100),
      percent(overhead / revenue * 100)
    ]);
    if (expectedQ9Choices.size !== 4) { q9Fallbacks++; expectedQ9Choices.add('100%'); }
    assert.deepEqual(new Set(q9.options.map(option => option.text)), expectedQ9Choices);
    portfolioVariants.add(JSON.stringify(q9.table.rows));

    const [benchCost, benchBilling] = amountsIn(q10.prompt);
    assert.ok(revenue > benchBilling);
    assert.ok(direct > benchCost, 'portfolio direct costs include the continuing payroll');
    assert.equal(correctText(paper, q10), `€${(gross - benchBilling).toLocaleString('en-GB')}`);

    const q11 = question(paper, 'Your Gross Margin % has dropped from ');
    const [priorRate, currentRate] = [...q11.prompt.matchAll(/\d+(?:\.\d+)?%/g)].map(m => Number(m[0].slice(0, -1)));
    assert.ok(currentRate < priorRate, 'Q11 always has a strict decline while revenue stays constant');
    assert.match(correctText(paper, q11), /Direct costs increased/);

    const q12 = question(paper, 'You have two consultants in your portfolio.');
    const cHeaders = q12.table.headers.slice(1);
    const cRows = new Map(q12.table.rows.map(([label, ...values]) => [label, values.map(money)]));
    const cRevenue = cRows.get('Monthly Billing');
    const cCosts = cRows.get('Monthly Cost');
    const cRates = cRevenue.map((value, i) => (value - cCosts[i]) / value * 100);
    assert.notEqual(cRates[0], cRates[1]);
    const cWinner = cRates[0] > cRates[1] ? 0 : 1;
    assert.equal(correctText(paper, q12), cHeaders[cWinner]);
    if (cWinner === 0) alphaWins++; else betaWins++;

    const q13 = question(paper, 'A client asks you to reduce the billing rate by ');
    const [rateBilling, rateCost] = amountsIn(q13.prompt);
    const discount = Number(q13.prompt.match(/by (\d+)%/)[1]);
    const before = rateBilling - rateCost;
    const discountValue = rateBilling * discount / 100;
    const after = before - discountValue;
    assert.equal(correctText(paper, q13), `It changes from €${before.toLocaleString('en-GB')} to €${after.toLocaleString('en-GB')}.`);

    const q15 = question(paper, 'You are comparing two Business Managers');
    const pHeaders = q15.table.headers.slice(1);
    const pRows = new Map(q15.table.rows.map(([label, ...values]) => [label, values.map(money)]));
    const pRevenue = pRows.get('Revenue');
    const pGross = pRows.get('Gross Margin');
    const pRates = pGross.map((value, i) => value / pRevenue[i] * 100);
    assert.notEqual(pRates[0], pRates[1]);
    const pWinner = pRates[0] > pRates[1] ? 0 : 1;
    assert.equal(correctText(paper, q15), pHeaders[pWinner]);
    if (pWinner === 0) bmAlphaWins++; else bmBetaWins++;
    assert.ok(q12.options.every(option => !/%/.test(option.text)), 'Q12 choices do not disclose the table-derived ratios');
    assert.ok(q15.options.every(option => !/%/.test(option.text)), 'Q15 choices do not disclose the table-derived ratios');
    if (pRevenue[0] !== pRevenue[1]) {
      if ((pRates[0] > pRates[1]) === (pRevenue[0] > pRevenue[1])) highRateAlsoHigherRevenue++;
      else highRateHasLowerRevenue++;
    }
  }
  assert.ok(portfolioVariants.size > 850, `sampled ${portfolioVariants.size} unique monthly P&Ls`);
  assert.ok(alphaWins > 0 && betaWins > 0, 'Q12 comparison winners vary');
  assert.ok(bmAlphaWins > 0 && bmBetaWins > 0, 'Q15 comparison winners vary');
  assert.ok(highRateAlsoHigherRevenue > 0 && highRateHasLowerRevenue > 0, 'Q15 does not encode revenue as a shortcut for percentage efficiency');
  assert.ok(q9Fallbacks > 0, 'Q9 deduplicates rounded operating and overhead percentages');
});

test('both sections and option positions are randomized without changing issued grading', () => {
  const papers = Array.from({ length: 40 }, () => makePaper());
  const signatures = papers.map(p => p.questions.map(q => q.prompt).join('|'));
  assert.ok(new Set(signatures).size > 1);
  const placements = papers.flatMap(p => p.questions.map(q => q.options.findIndex(o => o.id === p.key[q.id][0])));
  assert.equal(new Set(placements).size, 4);
  for (const paper of papers) assert.equal(grade(paper, paper.key), 15);
});
