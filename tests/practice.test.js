function fixture() {
  const limited = [];
  let rateDenied = false;
  const target = {
    PRACTICE_KEY: key,
    RATE_KEY: 'b'.repeat(64),
    RATE_LIMITER: { async limit({key: value}) { limited.push(value); return {success:!rateDenied}; } },
  };
  const env = new Proxy(target, {
    get(object, name) {
      if (['ATTEMPTS', 'RECORDS', 'OPS_TOKEN'].includes(name))
        throw new Error('Practice must not read hiring storage, operator access, or notice configuration.');
      return object[name];
    },
  });
  async function request(path, data, options = {}) {
    const headers = {...(options.headers ?? {})};
    if (options.origin !== null) headers.Origin = options.origin ?? origin;
    headers['CF-Connecting-IP'] = '192.0.2.40';
    if (data !== undefined) headers['Content-Type'] = options.contentType ?? 'application/json';
    return worker.fetch(new Request(origin + path, {
      method: options.method ?? 'POST', headers,
      body: data === undefined ? undefined : typeof data === 'string' ? data : JSON.stringify(data),
    }), env);
  }
  return {env, limited, request, setRateDenied(value) { rateDenied = value; }};
}

function amount(text) { return Number(text.replace(/[€,]/g, '')); }
function correctText(paper, question) {
  return question.options.find(option => option.id === paper.key[question.id])?.text;
}

test('practice paper matches the supplied 15-question paper, shuffles within its two sections, and keeps keys private', () => {
  const first = makePracticePaper();
  const second = makePracticePaper();
  const ids = new Set();
  const sectionIds = new Set();
  assert.equal(first.questions.length, 15);
  assert.deepEqual(first.questions.map(q => q.section), [
    ...Array(8).fill('Foundations'), ...Array(7).fill('Applied Reading'),
  ]);
  assert.deepEqual(first.referenceTable, {
    title: "Reference P&L — Business Manager's Monthly Portfolio",
    headers: ['Line Item', 'Amount (€)'],
    rows: [
      ['Revenue (client billing)', '€120,000'],
      ['Direct Costs (consultant salaries + charges)', '€78,000'],
      ['Gross Margin', '€42,000'],
      ['Allocated Overhead (office, support functions)', '€18,000'],
      ['Operating Result (Contribution)', '€24,000'],
    ],
  });
  for (const question of first.questions) {
    const canonical = Number(question.id.slice('practice-q'.length)) - 1;
    assert.ok(canonical >= 0 && canonical < 15);
    assert.equal(question.prompt, expected[canonical][0]);
    assert.deepEqual(new Set(question.options.map(option => option.text)), new Set(expected[canonical][1]));
    assert.equal(question.usesReferenceTable, canonical >= 8 && canonical <= 12 ? true : undefined);
    assert.deepEqual(Object.keys(question).sort(), [
      'id', 'options', 'prompt', 'section',
      ...(canonical >= 8 && canonical <= 12 ? ['usesReferenceTable'] : []),
      ...(canonical === 11 || canonical === 14 ? ['table'] : []),
    ].sort());
    assert.equal(question.options.length, 4);
    assert.equal(new Set(question.options.map(option => option.text)).size, 4);
    assert.equal(new Set(question.options.map(option => option.id)).size, 4);
    assert.ok(first.key[question.id]);
    assert.ok(question.options.some(option => option.id === first.key[question.id]));
    const expectedCorrect = expected[canonical][1][expected[canonical][2]];
    assert.equal(correctText(first, question), expectedCorrect);
    for (const option of question.options) {
      assert.deepEqual(Object.keys(option).sort(), ['id', 'text']);
      assert.match(option.id, hexId);
      assert.ok(!ids.has(option.id)); ids.add(option.id);
    }
    sectionIds.add(question.id);
  }
  assert.equal(sectionIds.size, 15);
  assert.match(first.questions.find(q => q.id === 'practice-q5').prompt, /€800.*€500/);
  assert.doesNotMatch(first.questions.find(q => q.id === 'practice-q5').prompt, /Question 4/);
  assert.match(first.questions.find(q => q.id === 'practice-q10').prompt, /cost remains included/);
  assert.equal(correctText(first, first.questions.find(q => q.id === 'practice-q10')), '€33,000');
  assert.deepEqual(first.questions.find(q => q.id === 'practice-q12').table, {
    headers: ['', 'Consultant A', 'Consultant B'],
    rows: [['Monthly Billing', '€8,000', '€12,000'], ['Monthly Cost', '€5,500', '€9,000']],
  });
  assert.deepEqual(first.questions.find(q => q.id === 'practice-q15').table, {
    headers: ['', 'BM Alpha', 'BM Beta'],
    rows: [['Revenue', '€300,000', '€500,000'], ['Gross Margin', '€90,000', '€120,000']],
  });
  assert.notDeepEqual(first.questions.map(q => q.id), second.questions.map(q => q.id), 'question order is freshly shuffled');
  for (const paper of [first, second]) {
    for (const question of paper.questions) {
      assert.equal(question.explanations, undefined);
      assert.equal(question.correct, undefined);
      assert.notEqual(paper.explanations[question.id].good, paper.explanations[question.id].bad);
    }
    const perfect = scorePractice(serverTicket(paper), paper.key);
    assert.equal(perfect.score, 15);
    assert.ok(perfect.review.every(item => item.outcome === 'good' && item.explanation === paper.explanations[item.id].good));
    const blank = scorePractice(serverTicket(paper), {});
    assert.equal(blank.score, 0);
    assert.equal(blank.total, 15);
    assert.equal(blank.answered, 0);
    assert.ok(blank.review.every(item => item.outcome === 'unanswered' && item.explanation === paper.explanations[item.id].bad));
    const oneWrong = {...paper.key};
    const question = paper.questions[0];
    oneWrong[question.id] = question.options.find(option => option.id !== paper.key[question.id]).id;
    const missed = scorePractice(serverTicket(paper), oneWrong);
    assert.equal(missed.score, 14);
    assert.equal(missed.review.find(item => item.id === question.id).outcome, 'bad');
  }
});

