// This module and each paper's grading key belong in the Worker only.
const euroFormatter = new Intl.NumberFormat('en-GB', { maximumFractionDigits: 0 });
const euros = value => '€' + euroFormatter.format(value);
const percent = value => Number(value.toFixed(1)) + '%';

const dailyBillings = [600, 800, 1000, 1200, 1400, 1600];
const dailyCostRates = [60, 62.5, 65, 67.5, 70, 72.5, 75];
const consultantBillings = [8000, 9000, 10000, 11000, 12000, 14000];
const consultantMarginRates = [25, 30, 35, 40, 45, 50, 55];
const bmRevenues = [200000, 250000, 300000, 350000, 400000, 450000, 500000, 600000, 700000, 800000];
const bmMarginRates = [30, 32, 34, 36, 38, 40, 42, 44, 46, 48, 50];

function indexBelow(limit) {
  const range = 0x100000000;
  const cutoff = range - range % limit;
  const word = new Uint32Array(1);
  do { crypto.getRandomValues(word); } while (word[0] >= cutoff);
  return word[0] % limit;
}

const pick = values => values[indexBelow(values.length)];
const pickInt = (minimum, maximum, step = 1) => minimum + indexBelow((maximum - minimum) / step + 1) * step;

function shuffle(values) {
  const result = [...values];
  for (let i = result.length - 1; i > 0; i--) {
    const j = indexBelow(i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function item(prompt, correct, ...alternatives) {
  const choices = [correct, ...alternatives];
  if (choices.length !== 4 || new Set(choices).size !== 4) throw new Error('Each hiring question must have four distinct choices.');
  return { prompt, correct, alternatives };
}

// End-of-paper teaching text. It stays off the question object sent during the attempt.
function explained(entry, because) {
  if (typeof because !== 'string' || because.trim().length < 20) throw new Error('Each hiring question must explain the other answers.');
  return { ...entry, explanation: `Good answer: ${entry.correct}. Why the others are not: ${because.trim()}` };
}

function table(headers, rows) { return { headers, rows }; }

function dailyCase() {
  const billing = pick(dailyBillings);
  const costRate = pick(dailyCostRates);
  const cost = billing * costRate / 100;
  return { billing, cost, costRate, gross: billing - cost };
}

function teamCase() {
  const headcount = pick([3, 4, 5, 6]);
  const billingPerConsultant = pick([7000, 8000, 9000, 10000, 11000, 12000, 14000, 15000]);
  const revenue = headcount * billingPerConsultant;
  const directCostRate = pick([60, 65, 70, 75]);
  const directCosts = revenue * directCostRate / 100;
  return { headcount, billingPerConsultant, revenue, directCosts, gross: revenue - directCosts };
}

export function makePortfolioCase(revenue, marginRate, overhead) {
  if (!Number.isInteger(revenue) || revenue < 90000 || revenue > 300000 || revenue % 100 !== 0 ||
      !Number.isInteger(marginRate) || marginRate < 28 || marginRate > 46) {
    throw new Error('Portfolio figures are outside the supported range.');
  }
  const gross = revenue * marginRate / 100;
  const directCosts = revenue - gross;
  const minimumOverhead = Math.ceil(revenue * 0.08 / 10) * 10;
  const maximumOverhead = Math.floor(Math.min(revenue * 0.24, gross - 1000) / 10) * 10;
  if (!Number.isInteger(overhead) || overhead < minimumOverhead || overhead > maximumOverhead || overhead % 10 !== 0)
    throw new Error('Portfolio overhead is outside the supported range.');
  return {
    revenue, marginRate, directCosts, gross, overhead,
    contribution: gross - overhead,
    table: table(['Line Item', 'Amount (€)'], [
      ['Revenue (client billing)', euros(revenue)],
      ['Direct Costs (consultant salaries + charges)', euros(directCosts)],
      ['Gross Margin', euros(gross)],
      ['Allocated Overhead (office, support functions)', euros(overhead)],
      ['Operating Result (Contribution)', euros(gross - overhead)]
    ])
  };
}

function portfolioCase() {
  const revenue = pickInt(90000, 300000, 100);
  const marginRate = pickInt(28, 46);
  const gross = revenue * marginRate / 100;
  const minimumOverhead = Math.ceil(revenue * 0.08 / 10) * 10;
  const maximumOverhead = Math.floor(Math.min(revenue * 0.24, gross - 1000) / 10) * 10;
  return makePortfolioCase(revenue, marginRate, pickInt(minimumOverhead, maximumOverhead, 10));
}

function foundations(daily, team) {
  const margin = euros(daily.gross);
  const billing = euros(daily.billing);
  const cost = euros(daily.cost);
  const teamMargin = euros(team.gross);
  const teamRevenue = euros(team.revenue);
  const teamCost = euros(team.directCosts);
  return [
    explained(item('What does P&L stand for?', 'Profit & Loss', 'Planning & Logistics', 'Profit & Liquidity', 'Performance & Leverage'),
      'Planning & Logistics, Profit & Liquidity, and Performance & Leverage are not the name of the profit and loss statement.'),
    explained(item('At Amaris, Revenue is primarily generated by:',
      "Billing consultants' services to clients at an agreed daily or monthly rate",
      'The number of consultants hired', 'The number of contracts signed per year', 'The overhead charged to support functions'),
      'Headcount, the number of contracts, and overhead charged to support functions do not themselves create client revenue.'),
    explained(item('In consulting, Gross Margin is best defined as:',
      'Revenue from client billing minus the direct cost of the consultants (salaries + charges)',
      'Total revenue before any deductions', 'Revenue minus all company overhead and administrative costs', 'Net income after taxes'),
      'Total revenue before deductions is revenue, not margin. Subtracting all overhead describes a result after indirect costs. Net income after taxes comes after every cost and tax.'),
    explained(item('A consultant is billed to a client at ' + billing + '/day. Their internal daily cost (salary + employer charges) is ' + cost + '/day. What is the Gross Margin per day?',
      margin, euros(daily.billing + daily.cost), billing, cost),
      euros(daily.billing + daily.cost) + ' adds billing and cost. ' + billing + ' is the billing rate alone, and ' + cost + ' is the cost alone.'),
    explained(item('A consultant bills ' + billing + ' per day and costs ' + cost + ' per day. What is the Gross Margin %?',
      percent(daily.gross / daily.billing * 100), percent(daily.costRate), percent(daily.gross / daily.cost * 100), '100%'),
      percent(daily.costRate) + ' is cost divided by billing. ' + percent(daily.gross / daily.cost * 100) + ' divides the margin by cost instead of billing. 100% would mean the consultant had no cost.'),
    explained(item('As a Business Manager at Amaris, which of the following is considered a direct cost on your P&L?',
      'The salary and social charges of your billable consultants', 'The rent of the Amaris head office', 'The marketing budget of the Amaris brand', "The CEO's compensation"),
      "Head-office rent, brand marketing, and the CEO's compensation are overhead, not the direct cost of billable consultants."),
    explained(item('One of your consultants is on the bench (not currently billed to any client) for a full month. Their salary is still being paid. What is the direct impact on your Gross Margin?',
      'Gross Margin decreases, as you bear the cost without generating revenue from this consultant', 'No impact, since the consultant is still employed', 'Gross Margin improves because there is no billing to manage', 'Gross Margin increases because the consultant is available'),
      'Employment alone does not keep the margin unchanged. Having nothing to bill does not improve it, and availability does not increase it.'),
    explained(item('You manage a team of ' + team.headcount + ' consultants, each billed at ' + euros(team.billingPerConsultant) + '/month to clients. The total monthly direct cost of the team is ' + teamCost + '. What is your team’s monthly Gross Margin?',
      teamMargin, teamCost, teamRevenue, euros(team.revenue + team.directCosts)),
      teamCost + ' is the direct cost, ' + teamRevenue + ' is the revenue, and ' + euros(team.revenue + team.directCosts) + ' adds those two figures.')
  ];
}

function marginDropQuestion() {
  const previousMargin = pick([36, 38, 40, 42, 44, 46]);
  const currentMargin = previousMargin - pick([4, 6, 8, 10]);
  return explained(item('Your Gross Margin % has dropped from ' + percent(previousMargin) + ' to ' + percent(currentMargin) + ' over the last quarter while revenue remained stable. Which is the most likely cause?',
    'Direct costs increased (e.g., salary raises or higher-cost profiles placed at the same billing rate)', 'Overhead costs increased', 'You hired additional support staff', 'Taxes on the entity increased'),
    'Higher overhead, extra support staff, and taxes sit below gross margin. With revenue unchanged, a lower gross margin means direct cost rose.');
}

function portfolioQuestion(portfolio) {
  const correct = percent(portfolio.gross / portfolio.revenue * 100);
  const distractors = [
    percent(portfolio.directCosts / portfolio.revenue * 100),
    percent(portfolio.contribution / portfolio.revenue * 100),
    percent(portfolio.overhead / portfolio.revenue * 100)
  ];
  if (new Set([correct, ...distractors]).size !== 4) distractors[1] = '100%';
  const [costShare, contributionShare, overheadShare] = distractors;
  const contributionReason = contributionShare === '100%'
    ? '100% would mean the portfolio had no cost'
    : contributionShare + ' is contribution divided by revenue (' + euros(portfolio.contribution) + ' / ' + euros(portfolio.revenue) + ')';
  return {
    ...explained(item('What is the Gross Margin % for this portfolio?', correct, ...distractors),
      costShare + ' is direct cost divided by revenue. ' + contributionReason + '. ' + overheadShare + ' is overhead divided by revenue. None of those is gross margin over revenue (' + euros(portfolio.gross) + ' / ' + euros(portfolio.revenue) + ').'),
    table: portfolio.table
  };
}

function benchPortfolioQuestion(portfolio) {
  const cases = [
    [8000, 5000], [9000, 6500], [10000, 7000], [12000, 8000], [14000, 9000], [16000, 10000]
  ];
  const [billing, continuingPayroll] = pick(cases);
  if (portfolio.revenue <= billing || portfolio.directCosts <= continuingPayroll)
    throw new Error('The shared P&L cannot support its bench-consultant case.');
  const next = euros(portfolio.gross - billing);
  const unchanged = euros(portfolio.gross);
  const minusPayroll = euros(portfolio.gross - continuingPayroll);
  const plusPayroll = euros(portfolio.gross - billing + continuingPayroll);
  return {
    ...explained(item('One consultant (monthly cost: ' + euros(continuingPayroll) + '; billing: ' + euros(billing) + ') is included in the monthly portfolio below. The consultant goes on the bench for a full month and their payroll remains in direct costs. What is the new Gross Margin for the month?',
      next, unchanged, minusPayroll, plusPayroll),
      unchanged + ' ignores the lost billing. ' + minusPayroll + ' subtracts payroll that is already inside direct costs. ' + plusPayroll + ' treats that payroll as if it had left the costs. Only the lost ' + euros(billing) + ' of billing comes out of gross margin.'),
    table: portfolio.table
  };
}

function consultantComparison() {
  const billings = [pick(consultantBillings), pick(consultantBillings)];
  const rateA = pick(consultantMarginRates);
  const rateB = pick(consultantMarginRates.filter(rate => rate !== rateA));
  const rates = [rateA, rateB];
  const costs = billings.map((billing, index) => billing * (100 - rates[index]) / 100);
  const names = ['Consultant A', 'Consultant B'];
  const winner = rateA > rateB ? 0 : 1;
  const marginRate = (billing, cost) => percent((billing - cost) / billing * 100);
  return {
    ...explained(item('You have two consultants in your portfolio. Which generates a better Gross Margin %?',
      names[winner], names[1 - winner],
      'They are equal', 'Cannot be determined'),
      names[1 - winner] + ' earns ' + marginRate(billings[1 - winner], costs[1 - winner]) + ', below ' + names[winner] + ' at ' + marginRate(billings[winner], costs[winner]) + '. The rates differ, so they are not equal, and both can be calculated from the table.'),
    table: table(['', ...names], [
      ['Monthly Billing', ...billings.map(euros)],
      ['Monthly Cost', ...costs.map(euros)]
    ])
  };
}

function rateReduction() {
  const billing = pick([8000, 9000, 10000, 12000, 14000, 16000, 18000]);
  const costRate = pick([60, 65, 70]);
  const cost = billing * costRate / 100;
  const reduction = pick([5, 10, 15]);
  const reductionValue = billing * reduction / 100;
  const before = billing - cost;
  const after = before - reductionValue;
  return explained(item('A client asks you to reduce the billing rate by ' + reduction + '% for one consultant currently billed at ' + euros(billing) + '/month. The consultant’s cost remains at ' + euros(cost) + '/month. What happens to the Gross Margin on this consultant?',
    'It changes from ' + euros(before) + ' to ' + euros(after) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(before) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(after - reductionValue) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(billing - reductionValue) + '.'),
    'Leaving the margin at ' + euros(before) + ' ignores the ' + euros(reductionValue) + ' price cut. ' + euros(after - reductionValue) + ' subtracts that cut twice. ' + euros(billing - reductionValue) + ' is the new billing, not the margin after the unchanged ' + euros(cost) + ' cost.');
}

function directAction() {
  return explained(item('As a Business Manager, which of the following actions has the most direct positive impact on your Gross Margin?',
    'Placing a bench consultant quickly at a billing rate above their cost', 'Reducing the number of internal meetings', 'Requesting a lower office space allocation', 'Hiring a new support profile in your team'),
    'Fewer internal meetings do not change gross margin. A smaller office allocation and a new support profile are overhead, not gross margin.');
}

function portfolioComparison() {
  const rates = shuffle(bmMarginRates).slice(0, 2);
  const revenues = [pick(bmRevenues), pick(bmRevenues)];
  const gross = revenues.map((revenue, index) => revenue * rates[index] / 100);
  const names = ['BM Alpha', 'BM Beta'];
  const winner = rates[0] > rates[1] ? 0 : 1;
  return {
    ...explained(item('You are comparing two Business Managers’ portfolios at end of quarter. Which portfolio is more efficient from a Gross Margin % perspective?',
      names[winner], names[1 - winner],
      'Both portfolios are equally efficient', 'There is not enough information to compare them'),
      names[1 - winner] + ' is at ' + percent(rates[1 - winner]) + ', below ' + names[winner] + ' at ' + percent(rates[winner]) + '. ' + euros(gross[1 - winner]) + ' can be a larger euro margin and still be a weaker percentage. The percentages differ, and the table is enough to compare them.'),
    table: table(['', ...names], [
      ['Revenue', ...revenues.map(euros)],
      ['Gross Margin', ...gross.map(euros)]
    ])
  };
}

function applied(portfolio) {
  return [
    portfolioQuestion(portfolio),
    benchPortfolioQuestion(portfolio),
    marginDropQuestion(),
    consultantComparison(),
    rateReduction(),
    directAction(),
    portfolioComparison()
  ];
}

export function makePaper() {
  const daily = dailyCase();
  const team = teamCase();
  const portfolio = portfolioCase();
  const questions = [];
  const key = {};
  const notes = {};
  const sections = [
    ['Foundations', foundations(daily, team)],
    ['Applied Reading', applied(portfolio)]
  ];
  for (const [section, entries] of sections) {
    for (const entry of shuffle(entries)) {
      if (typeof entry.explanation !== 'string' || !entry.explanation.startsWith(`Good answer: ${entry.correct}.`))
        throw new Error('Each hiring question needs an explanation that stays off the candidate paper.');
      const id = crypto.randomUUID();
      const options = shuffle([entry.correct, ...entry.alternatives].map(text => ({ id: crypto.randomUUID(), text })));
      key[id] = [options.find(option => option.text === entry.correct).id];
      notes[id] = entry.explanation;
      const question = { id, section, prompt: entry.prompt, options };
      if (entry.table) question.table = entry.table;
      questions.push(question);
    }
  }
  return { questions, key, notes };
}

export function grade(paper, answers) {
  let score = 0;
  for (const { id } of paper.questions) {
    const selected = answers?.[id];
    if (Array.isArray(selected) && selected.length === 1 && selected[0] === paper.key[id][0]) score++;
  }
  return score;
}

export function reviewPaper(paper, answers) {
  return paper.questions.map(question => {
    const selectedIds = Array.isArray(answers?.[question.id]) ? answers[question.id] : [];
    const yours = question.options.filter(option => selectedIds.includes(option.id)).map(option => option.text);
    const good = question.options.find(option => option.id === paper.key[question.id][0]).text;
    const matched = selectedIds.length === 1 && selectedIds[0] === paper.key[question.id][0];
    return {
      prompt: question.prompt,
      section: question.section,
      yours: yours.length ? yours.join('; ') : null,
      good,
      matched,
      explanation: paper.notes[question.id],
    };
  });
}
