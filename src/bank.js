const euroFormatter = new Intl.NumberFormat('en-GB', { maximumFractionDigits: 0 });
const euros = value => '€' + euroFormatter.format(value);
const percent = value => Number(value.toFixed(1)) + '%';

const dailyBillings = [600, 800, 1000, 1200, 1400, 1600];
const dailyCostRates = [60, 62.5, 65, 67.5, 70, 72.5, 75];
const consultantBillings = [8000, 9000, 10000, 11000, 12000, 14000];
const consultantMarginRates = [25, 30, 35, 40, 45, 50, 55];
const bmRevenues = [200000, 250000, 300000, 350000, 400000, 450000, 500000, 600000, 700000, 800000];
const bmMarginRates = [30, 32, 34, 36, 38, 40, 42, 44, 46, 48, 50];

function indexBelow(limit) {
  const range = 0x100000000;
  const cutoff = range - range % limit;
  const word = new Uint32Array(1);
  do { crypto.getRandomValues(word); } while (word[0] >= cutoff);
  return word[0] % limit;
}

const pick = values => values[indexBelow(values.length)];
const pickInt = (minimum, maximum, step = 1) => minimum + indexBelow((maximum - minimum) / step + 1) * step;

function shuffle(values) {
  const result = [...values];
  for (let i = result.length - 1; i > 0; i--) {
    const j = indexBelow(i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function item(prompt, correct, ...rest) {
  const explanations = rest.length && typeof rest[rest.length - 1] === 'object' ? rest.pop() : null;
  const alternatives = rest;
  const choices = [correct, ...alternatives];
  if (choices.length !== 4 || new Set(choices).size !== 4) throw new Error('Each hiring question must have four distinct choices.');
  if (!explanations || typeof explanations.good !== 'string' || typeof explanations.bad !== 'string' ||
      explanations.good.trim().length < 12 || explanations.bad.trim().length < 12 || explanations.good === explanations.bad ||
      Object.keys(explanations).length !== 2) {
    throw new Error('Each hiring question needs distinct good and bad explanations.');
  }
  return { prompt, correct, alternatives, explanations };
}

function table(headers, rows) { return { headers, rows }; }

function dailyCase() {
  const billing = pick(dailyBillings);
  const costRate = pick(dailyCostRates);
  const cost = billing * costRate / 100;
  return { billing, cost, costRate, gross: billing - cost };
}

function teamCase() {
  const headcount = pick([3, 4, 5, 6]);
  const billingPerConsultant = pick([7000, 8000, 9000, 10000, 11000, 12000, 14000, 15000]);
  const revenue = headcount * billingPerConsultant;
  const directCostRate = pick([60, 65, 70, 75]);
  const directCosts = revenue * directCostRate / 100;
  return { headcount, billingPerConsultant, revenue, directCosts, gross: revenue - directCosts };
}

export function makePortfolioCase(revenue, marginRate, overhead) {
  if (!Number.isInteger(revenue) || revenue < 90000 || revenue > 300000 || revenue % 100 !== 0 ||
      !Number.isInteger(marginRate) || marginRate < 28 || marginRate > 46) {
    throw new Error('Portfolio figures are outside the supported range.');
  }
  const gross = revenue * marginRate / 100;
  const directCosts = revenue - gross;
  const minimumOverhead = Math.ceil(revenue * 0.08 / 10) * 10;
  const maximumOverhead = Math.floor(Math.min(revenue * 0.24, gross - 1000) / 10) * 10;
  if (!Number.isInteger(overhead) || overhead < minimumOverhead || overhead > maximumOverhead || overhead % 10 !== 0)
    throw new Error('Portfolio overhead is outside the supported range.');
  return {
    revenue, marginRate, directCosts, gross, overhead,
    contribution: gross - overhead,
    table: table(['Line Item', 'Amount (€)'], [
      ['Revenue (client billing)', euros(revenue)],
      ['Direct Costs (consultant salaries + charges)', euros(directCosts)],
      ['Gross Margin', euros(gross)],
      ['Allocated Overhead (office, support functions)', euros(overhead)],
      ['Operating Result (Contribution)', euros(gross - overhead)]
    ])
  };
}

function portfolioCase() {
  const revenue = pickInt(90000, 300000, 100);
  const marginRate = pickInt(28, 46);
  const gross = revenue * marginRate / 100;
  const minimumOverhead = Math.ceil(revenue * 0.08 / 10) * 10;
  const maximumOverhead = Math.floor(Math.min(revenue * 0.24, gross - 1000) / 10) * 10;
  return makePortfolioCase(revenue, marginRate, pickInt(minimumOverhead, maximumOverhead, 10));
}

function foundations(daily, team) {
  const marginPercent = percent(daily.gross / daily.billing * 100);
  return [
    item('What does P&L stand for?', 'Profit & Loss', 'Planning & Logistics', 'Profit & Liquidity', 'Performance & Leverage', {
      good: 'P&L means Profit & Loss, the statement that sets revenue against costs.',
      bad: 'P&L means Profit & Loss. Planning & Logistics, Profit & Liquidity, and Performance & Leverage are not this statement.',
    }),
    item('At Amaris, Revenue is primarily generated by:',
      "Billing consultants' services to clients at an agreed daily or monthly rate",
      'The number of consultants hired', 'The number of contracts signed per year', 'The overhead charged to support functions', {
        good: "Revenue comes from billing consultants' services to clients at an agreed daily or monthly rate.",
        bad: "Headcount, contract counts, and overhead do not create revenue. Revenue comes from billing consultants' services to clients.",
      }),
    item('In consulting, Gross Margin is best defined as:',
      'Revenue from client billing minus the direct cost of the consultants (salaries + charges)',
      'Total revenue before any deductions', 'Revenue minus all company overhead and administrative costs', 'Net income after taxes', {
        good: 'Gross margin is revenue from client billing minus the direct cost of the consultants (salaries + charges).',
        bad: 'Gross margin is not total revenue, profit after overhead, or net income. It is client billing minus consultant direct cost.',
      }),
    item('A consultant is billed to a client at ' + euros(daily.billing) + '/day. Their internal daily cost (salary + employer charges) is ' + euros(daily.cost) + '/day. What is the Gross Margin per day?',
      euros(daily.gross), euros(daily.billing + daily.cost), euros(daily.billing), euros(daily.cost), {
        good: 'Gross margin per day is billing minus internal cost: ' + euros(daily.billing) + ' − ' + euros(daily.cost) + ' = ' + euros(daily.gross) + '.',
        bad: 'The sum of billing and cost, or either figure alone, is not gross margin. ' + euros(daily.billing) + ' − ' + euros(daily.cost) + ' = ' + euros(daily.gross) + '.',
      }),
    item('A consultant bills ' + euros(daily.billing) + ' per day and costs ' + euros(daily.cost) + ' per day. What is the Gross Margin %?',
      marginPercent, percent(daily.costRate), percent(daily.gross / daily.cost * 100), '100%', {
        good: 'Gross margin % is (billing − cost) / billing: (' + euros(daily.billing) + ' − ' + euros(daily.cost) + ') / ' + euros(daily.billing) + ' = ' + marginPercent + '.',
        bad: 'The cost ratio, a markup on cost, and 100% are not gross margin %. (' + euros(daily.billing) + ' − ' + euros(daily.cost) + ') / ' + euros(daily.billing) + ' = ' + marginPercent + '.',
      }),
    item('As a Business Manager at Amaris, which of the following is considered a direct cost on your P&L?',
      'The salary and social charges of your billable consultants', 'The rent of the Amaris head office', 'The marketing budget of the Amaris brand', "The CEO's compensation", {
        good: 'The salary and social charges of billable consultants are a direct cost.',
        bad: 'Office rent, brand marketing, and CEO compensation are not direct costs. The direct cost is consultant salary and social charges.',
      }),
    item('One of your consultants is on the bench (not currently billed to any client) for a full month. Their salary is still being paid. What is the direct impact on your Gross Margin?',
      'Gross Margin decreases, as you bear the cost without generating revenue from this consultant', 'No impact, since the consultant is still employed', 'Gross Margin improves because there is no billing to manage', 'Gross Margin increases because the consultant is available', {
        good: 'A bench consultant still costs salary and produces no revenue, so gross margin decreases.',
        bad: 'Staying employed, easier billing, or availability does not protect the margin. Unbilled salary makes gross margin decrease.',
      }),
    item('You manage a team of ' + team.headcount + ' consultants, each billed at ' + euros(team.billingPerConsultant) + '/month to clients. The total monthly direct cost of the team is ' + euros(team.directCosts) + '. What is your team’s monthly Gross Margin?',
      euros(team.gross), euros(team.directCosts), euros(team.revenue), euros(team.revenue + team.directCosts), {
        good: 'Team gross margin is total billing minus direct cost: ' + team.headcount + ' × ' + euros(team.billingPerConsultant) + ' − ' + euros(team.directCosts) + ' = ' + euros(team.gross) + '.',
        bad: 'The cost total, the revenue total, and their sum are not the margin. ' + team.headcount + ' × ' + euros(team.billingPerConsultant) + ' − ' + euros(team.directCosts) + ' = ' + euros(team.gross) + '.',
      }),
  ];
}

function marginDropQuestion() {
  const previousMargin = pick([36, 38, 40, 42, 44, 46]);
  const currentMargin = previousMargin - pick([4, 6, 8, 10]);
  return item('Your Gross Margin % has dropped from ' + percent(previousMargin) + ' to ' + percent(currentMargin) + ' over the last quarter while revenue remained stable. Which is the most likely cause?',
    'Direct costs increased (e.g., salary raises or higher-cost profiles placed at the same billing rate)', 'Overhead costs increased', 'You hired additional support staff', 'Taxes on the entity increased', {
      good: 'Stable revenue and a lower gross margin % mean direct costs rose, such as salary increases or costlier profiles at the same rate.',
      bad: 'Overhead, support hiring, and taxes sit below gross margin. Stable revenue with a lower gross margin % means direct costs rose.',
    });
}

function portfolioQuestion(portfolio) {
  const correct = percent(portfolio.gross / portfolio.revenue * 100);
  const distractors = [
    percent(portfolio.directCosts / portfolio.revenue * 100),
    percent(portfolio.contribution / portfolio.revenue * 100),
    percent(portfolio.overhead / portfolio.revenue * 100)
  ];
  if (new Set([correct, ...distractors]).size !== 4) distractors[1] = '100%';
  return {
    ...item('What is the Gross Margin % for this portfolio?', correct, ...distractors, {
      good: 'Gross margin % is gross margin divided by revenue: ' + euros(portfolio.gross) + ' / ' + euros(portfolio.revenue) + ' = ' + correct + '.',
      bad: 'Direct-cost, contribution, and overhead ratios are different measures. Gross margin % is ' + euros(portfolio.gross) + ' / ' + euros(portfolio.revenue) + ' = ' + correct + '.',
    }),
    table: portfolio.table
  };
}

function benchPortfolioQuestion(portfolio) {
  const cases = [
    [8000, 5000], [9000, 6500], [10000, 7000], [12000, 8000], [14000, 9000], [16000, 10000]
  ];
  const [billing, continuingPayroll] = pick(cases);
  if (portfolio.revenue <= billing || portfolio.directCosts <= continuingPayroll)
    throw new Error('The shared P&L cannot support its bench-consultant case.');
  const revised = euros(portfolio.gross - billing);
  return {
    ...item('One consultant (monthly cost: ' + euros(continuingPayroll) + '; billing: ' + euros(billing) + ') is included in the monthly portfolio below. The consultant goes on the bench for a full month and their payroll remains in direct costs. What is the new Gross Margin for the month?',
      euros(portfolio.gross - billing),
      euros(portfolio.gross),
      euros(portfolio.gross - continuingPayroll),
      euros(portfolio.gross - billing + continuingPayroll), {
        good: 'Billing stops while payroll stays in direct costs, so lost billing comes out of gross margin: ' + euros(portfolio.gross) + ' − ' + euros(billing) + ' = ' + revised + '.',
        bad: 'The margin does not stay flat, and subtracting or adding payroll does not describe the bench month. ' + euros(portfolio.gross) + ' − ' + euros(billing) + ' = ' + revised + '.',
      }),
    table: portfolio.table
  };
}

function consultantComparison() {
  const billings = [pick(consultantBillings), pick(consultantBillings)];
  const rateA = pick(consultantMarginRates);
  const rateB = pick(consultantMarginRates.filter(rate => rate !== rateA));
  const rates = [rateA, rateB];
  const costs = billings.map((billing, index) => billing * (100 - rates[index]) / 100);
  const names = ['Consultant A', 'Consultant B'];
  const winner = rateA > rateB ? 0 : 1;
  const marginOf = index => percent((billings[index] - costs[index]) / billings[index] * 100);
  return {
    ...item('You have two consultants in your portfolio. Which generates a better Gross Margin %?',
      names[winner], names[1 - winner],
      'They are equal', 'Cannot be determined', {
        good: names[winner] + ' has the higher gross margin % at ' + marginOf(winner) + ', ahead of ' + names[1 - winner] + ' at ' + marginOf(1 - winner) + '.',
        bad: 'A larger billing amount is not a higher rate. ' + names[winner] + ' leads at ' + marginOf(winner) + ' versus ' + marginOf(1 - winner) + ' for ' + names[1 - winner] + '.',
      }),
    table: table(['', ...names], [
      ['Monthly Billing', ...billings.map(euros)],
      ['Monthly Cost', ...costs.map(euros)]
    ])
  };
}

function rateReduction() {
  const billing = pick([8000, 9000, 10000, 12000, 14000, 16000, 18000]);
  const costRate = pick([60, 65, 70]);
  const cost = billing * costRate / 100;
  const reduction = pick([5, 10, 15]);
  const reductionValue = billing * reduction / 100;
  const before = billing - cost;
  const after = before - reductionValue;
  return item('A client asks you to reduce the billing rate by ' + reduction + '% for one consultant currently billed at ' + euros(billing) + '/month. The consultant’s cost remains at ' + euros(cost) + '/month. What happens to the Gross Margin on this consultant?',
    'It changes from ' + euros(before) + ' to ' + euros(after) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(before) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(after - reductionValue) + '.',
    'It changes from ' + euros(before) + ' to ' + euros(billing - reductionValue) + '.', {
      good: 'A ' + reduction + '% cut removes ' + euros(reductionValue) + ' of billing while cost stays ' + euros(cost) + ', so gross margin moves from ' + euros(before) + ' to ' + euros(after) + '.',
      bad: 'The margin does not stay flat or absorb a second cut. Removing ' + euros(reductionValue) + ' of billing moves it from ' + euros(before) + ' to ' + euros(after) + '.',
    });
}

function directAction() {
  return item('As a Business Manager, which of the following actions has the most direct positive impact on your Gross Margin?',
    'Placing a bench consultant quickly at a billing rate above their cost', 'Reducing the number of internal meetings', 'Requesting a lower office space allocation', 'Hiring a new support profile in your team', {
      good: 'Placing a bench consultant above their cost adds revenue over direct cost and lifts gross margin.',
      bad: 'Fewer meetings, a smaller office, and a new support profile do not add client billing above direct cost. Placing a bench consultant above cost does.',
    });
}

function portfolioComparison() {
  const rates = shuffle(bmMarginRates).slice(0, 2);
  const revenues = [pick(bmRevenues), pick(bmRevenues)];
  const gross = revenues.map((revenue, index) => revenue * rates[index] / 100);
  const names = ['BM Alpha', 'BM Beta'];
  const winner = rates[0] > rates[1] ? 0 : 1;
  return {
    ...item('You are comparing two Business Managers’ portfolios at end of quarter. Which portfolio is more efficient from a Gross Margin % perspective?',
      names[winner], names[1 - winner],
      'Both portfolios are equally efficient', 'There is not enough information to compare them', {
        good: 'Efficiency is the gross margin rate, not the larger euro amount. ' + names[winner] + ' at ' + percent(rates[winner]) + ' beats ' + names[1 - winner] + ' at ' + percent(rates[1 - winner]) + '.',
        bad: 'A larger euro gross margin can still be a lower rate. ' + names[winner] + ' at ' + percent(rates[winner]) + ' is ahead of ' + names[1 - winner] + ' at ' + percent(rates[1 - winner]) + '.',
      }),
    table: table(['', ...names], [
      ['Revenue', ...revenues.map(euros)],
      ['Gross Margin', ...gross.map(euros)]
    ])
  };
}

function applied(portfolio) {
  return [
    portfolioQuestion(portfolio),
    benchPortfolioQuestion(portfolio),
    marginDropQuestion(),
    consultantComparison(),
    rateReduction(),
    directAction(),
    portfolioComparison()
  ];
}

export function makePaper() {
  const daily = dailyCase();
  const team = teamCase();
  const portfolio = portfolioCase();
  const questions = [];
  const key = {};
  const explanations = {};
  const sections = [
    ['Foundations', foundations(daily, team)],
    ['Applied Reading', applied(portfolio)]
  ];
  for (const [section, entries] of sections) {
    for (const entry of shuffle(entries)) {
      const id = crypto.randomUUID();
      const options = shuffle([entry.correct, ...entry.alternatives].map(text => ({ id: crypto.randomUUID(), text })));
      key[id] = [options.find(option => option.text === entry.correct).id];
      explanations[id] = entry.explanations;
      const question = { id, section, prompt: entry.prompt, options };
      if (entry.table) question.table = entry.table;
      questions.push(question);
    }
  }
  return { questions, key, explanations };
}

export function reviewPaper(paper, answers) {
  return paper.questions.map(question => {
    const selected = answers?.[question.id];
    const answered = Array.isArray(selected) && selected.length > 0;
    const good = answered && selected.length === 1 && selected[0] === paper.key[question.id]?.[0];
    const pair = paper.explanations?.[question.id];
    if (!pair?.good || !pair?.bad) throw new Error('The issued paper is missing an explanation.');
    return {
      id: question.id,
      prompt: question.prompt,
      outcome: good ? 'good' : answered ? 'bad' : 'unanswered',
      explanation: good ? pair.good : pair.bad,
    };
  });
}

export function grade(paper, answers) {
  let score = 0;
  for (const { id } of paper.questions) {
    const selected = answers?.[id];
    if (Array.isArray(selected) && selected.length === 1 && selected[0] === paper.key[id][0]) score++;
  }
  return score;
}
